<?php

namespace Parse\AdminPanel\Authorization;

use Illuminate\Filesystem\Filesystem;
use InvalidArgumentException;
use Parse\AdminPanel\Infrastructure\Laravel\Panel\PanelManager;
use Parse\AdminPanel\Infrastructure\Laravel\Panel\PanelRuntime;

final class PermissionManifest
{
    public const array MANAGEMENT = ['roles.viewAny', 'roles.view', 'roles.create', 'roles.update', 'roles.delete', 'users.assignRoles'];

    public function __construct(private Filesystem $files) {}

    /** @return list<string> */
    public static function normalize(mixed $names): array
    {
        if (! is_array($names) || ! array_is_list($names)) {
            throw new InvalidArgumentException('Permissions must be a list of permission keys.');
        }
        foreach ($names as $name) {
            if (! is_string($name) || trim($name) === '' || trim($name) !== $name || mb_strlen($name) > 255) {
                throw new InvalidArgumentException('Permission keys must be non-empty strings of at most 255 characters without surrounding whitespace.');
            }
        }
        $names = array_values(array_unique($names));
        sort($names, SORT_STRING);

        return $names;
    }

    public function path(PanelRuntime $panel): string
    {
        $path = $panel->permissionsFile ?? 'config/admin-panel-permissions.php';
        if (str_starts_with($path, '/') || str_contains($path, '\\') || preg_match('/^[A-Za-z]:/', $path) || in_array('..', explode('/', $path), true) || ! str_ends_with($path, '.php')) {
            throw new InvalidArgumentException('permissions_file must be a project-relative PHP file path.');
        }

        $absolute = base_path(implode('/', array_filter(explode('/', $path), fn (string $segment): bool => $segment !== '' && $segment !== '.')));
        foreach (app(PanelManager::class)->panels() as $other) {
            if ($other->id !== $panel->id && $other->authorizationEnabled
                && base_path(implode('/', array_filter(explode('/', $other->permissionsFile ?? 'config/admin-panel-permissions.php'), fn (string $segment): bool => $segment !== '' && $segment !== '.'))) === $absolute) {
                throw new InvalidArgumentException('Panels must use separate permissions_file paths. Conflict with panel ['.$other->id.'].');
            }
        }

        return $absolute;
    }

    /** @return array<array-key, mixed> */
    private function load(PanelRuntime $panel): array
    {
        $path = $this->path($panel);
        if (! $this->files->exists($path)) {
            return [];
        }
        $data = $this->files->getRequire($path);
        if (! is_array($data)) {
            throw new InvalidArgumentException("Permission manifest [{$path}] must return an array.");
        }

        return $data;
    }

    /** @return list<string> */
    public function read(PanelRuntime $panel, bool $required = true): array
    {
        $data = $this->load($panel);
        if ($required && ! $this->files->exists($this->path($panel))) {
            throw new InvalidArgumentException('Permission manifest is missing for this panel; generate and deploy it first.');
        }

        return self::normalize($data);
    }

    /** @param list<string> $names
     * @return list<string>
     */
    public function generatedNames(PanelRuntime $panel, array $names): array
    {
        return self::normalize([...self::MANAGEMENT, ...$panel->permissions, ...$names]);
    }

    /** @param list<string> $names */
    public function contents(PanelRuntime $panel, array $names): string
    {
        $this->path($panel);
        $data = self::normalize($names);
        $lines = array_map(fn (string $name): string => '    '.var_export($name, true).',', $data);

        return "<?php\n\n// Generated by admin-panel:generate. Declare custom permissions in panel configuration.\nreturn [\n".implode("\n", $lines).($lines === [] ? '' : "\n")."];\n";
    }

    /** @param list<string> $names */
    public function write(PanelRuntime $panel, array $names): void
    {
        $contents = $this->contents($panel, $names);
        $path = $this->path($panel);
        $this->files->ensureDirectoryExists(dirname($path));
        $this->files->replace($path, $contents);
    }
}
